/* ════════════════════════════════════════════════════════════
   받아오는 자료가 사는 곳 — 배포 볼륨을 붙일 수 있게 한 곳으로 모은다

   ── 왜 만들었나 (사용자 지시 2026-09-10) ────────────────────
   "배포에 시간이 너무 걸린다." 재 보니 원인은 파일 크기가 아니라 `npm run build` 였다.
   배포마다 외부 자료 4종을 **순차로** 새로 받는데, 대부분이 크롤링 예의를 지키느라
   자는 시간이다 — 고용24 238페이지 × 1.2초, 위비티 (30페이지 + 상세 80건) × 3초.
   합계 13~17분이고 그중 10분 남짓이 sleep 이었다.

   근본 원인은 **디스크가 일회용**이라는 것이다. Railway 는 배포마다 컨테이너를 새로
   만들어 갈아 끼우므로, 지난 배포 때 받아 둔 11MB 짜리 공고 캐시가 통째로 사라진다.
   그래서 매번 처음부터 다시 받는다.

   ── 볼륨 ────────────────────────────────────────────────────
   컨테이너 밖에 붙는 디스크다. 배포해도 안 지워지고 새 컨테이너에 다시 꽂힌다.
   캐시가 살아남으면 daily-refresh 가 "20시간 이내 자료라 그대로 씁니다" 로 건너뛰므로,
   **배포는 1~2분이고 자료는 즉시 있다.**

   ── 그런데 data/ 에 그냥 붙이면 서버가 깨진다 ───────────────
   볼륨은 마운트한 경로의 **이미지 속 내용을 가린다.** 그런데 `backend/data` 에는
   받아오는 파일만 있는 게 아니라 **깃으로 함께 배포되는 파일이 18개**(자격증·학과·
   업종분류·NCS 등 약 2MB) 들어 있다. 거기에 볼륨을 붙이면 그것들이 통째로 안 보여서
   서버가 그 자리에서 깨진다.

   그래서 **받아오는 것만** 이 모듈의 경로로 옮긴다. 볼륨은 그 경로에 붙는다.
     · 깃으로 배포되는 정적 자료 → backend/data (그대로)
     · 받아서 쌓이는 캐시       → CACHE_DIR (볼륨)

   ── 쓰는 법 ─────────────────────────────────────────────────
   CACHE_DIR 을 안 주면 예전과 똑같이 backend/data 를 쓴다. 로컬 개발·테스트는
   설정을 바꿀 필요가 없다. 배포에서만 볼륨 경로를 준다:
     CACHE_DIR=/data        (Railway 볼륨 Mount path 와 같은 값)
   ════════════════════════════════════════════════════════════ */
const fs = require('fs');
const path = require('path');

const DEFAULT_DIR = path.join(__dirname, '..', 'data');

/* 상대 경로로 줘도 되게 resolve 한다 — 서버를 어느 디렉터리에서 띄우든 같은 곳을
   가리켜야 한다(로컬은 backend/, 배포는 저장소 루트에서 뜬다). */
const CACHE_DIR = process.env.CACHE_DIR
  ? path.resolve(process.env.CACHE_DIR)
  : DEFAULT_DIR;

const usingVolume = CACHE_DIR !== DEFAULT_DIR;

/* 볼륨은 **빈 채로** 처음 붙는다. 폴더가 없으면 첫 수집이 ENOENT 로 죽으므로
   여기서 한 번 만들어 둔다. 이미 있으면 아무 일도 없다. */
try { fs.mkdirSync(CACHE_DIR, { recursive: true }); }
catch (e) {
  /* 못 만들면 캐시 경로가 통째로 쓸모없다 — 조용히 넘어가면 수집이 매번 실패하고
     그 이유가 로그 어디에도 안 남는다. 크게 말하고 기본 경로로 물러난다. */
  console.error(`[cache] CACHE_DIR 를 만들지 못했습니다: ${CACHE_DIR} — ${e.message}`);
}

const cachePath = (...parts) => path.join(CACHE_DIR, ...parts);

/* 부팅 로그에 한 줄 남긴다. 볼륨이 안 붙은 채로 떠 있는 것을 모르면
   "왜 배포마다 또 받지?" 를 한참 헤맨다. */
function describe() {
  return usingVolume
    ? `[cache] 받아오는 자료: ${CACHE_DIR} (볼륨)`
    : `[cache] 받아오는 자료: backend/data (볼륨 없음 — 재배포하면 다시 받습니다)`;
}

module.exports = { CACHE_DIR, DEFAULT_DIR, cachePath, usingVolume, describe };
