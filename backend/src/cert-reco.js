/* 자격 하나의 시행기관. 모르면 null 을 준다 — 화면은 null 이면 빈칸을 내주고
   학생이 직접 적는다. 추측해서 채우면 틀린 값이 조용히 저장된다. */
function issuerOf(cert) {
  const name = String(cert?.id ?? cert?.name ?? cert ?? '');
  if (!name) return null;
  if (cert && cert.kind === 'private') return PRIVATE_ISSUERS[name] || null;
  return qnetIssuer(name);
}

function qnetIssuer(name) {
  const hit = ISSUER_EXCEPTIONS.find(([prefix]) => String(name || '').startsWith(prefix));
  return hit ? hit[1] : QNET_DEFAULT_ISSUER;
}

/* ── 공고 언급 집계 ────────────────────────────────────────────
   캐시 파일을 한 번 읽어 { NCS대분류 → { 자격증명 → 건수 } } 로 만든다.
   프로세스가 사는 동안 다시 계산하지 않는다 — 파일이 1MB 고 자격 이름이 600개라
   요청마다 돌리면 곱해진다.

   ── 짧은 이름은 세지 않는다 ──
   '연구'·'감정사' 같은 이름은 공고 본문 아무 데나 들어 있어서 그대로 찾으면
   전부 오탐이다. 4글자 미만은 빼고, 남은 것도 **자격증 이름 그대로** 들어 있을
   때만 센다(형태소 분석 없이 할 수 있는 선이 여기까지다).

   ── 모집이 끝난 공고는 빼지 않는다 ──
   캐시는 수집 시점에 '모집 중' 이던 것만 담겨 있다(fetch-alio-jobs.js). 여기서
   날짜로 또 거르면 캐시가 오래됐을 때 집계가 통째로 0이 되는데, 그건 '요구하는
   자격이 없다' 로 잘못 읽힌다. 대신 언제 수집한 것인지를 함께 내려보낸다. */
let _postings = null;

function loadPostings(certNames) {
  if (_postings) return _postings;

  let raw = null;
  try { raw = JSON.parse(fs.readFileSync(ALIO_PATH, 'utf8')); }
  catch {
    _postings = { fetchedAt: null, total: 0, byNcs: new Map(), byCert: new Map() };
    return _postings;
  }

  const items = Array.isArray(raw.items) ? raw.items : [];
  const targets = certNames.filter(n => n.length >= 4);
  const byNcs = new Map();      // NCS → Map(cert → { count, samples })
  const byCert = new Map();     // cert → 전체 건수

  items.forEach(j => {
    const text = `${j.aplyQlfcCn || ''} ${j.prefCn || ''} ${j.recrutPbancTtl || ''}`;
    if (!text.trim()) return;
    const fields = String(j.ncsCdNmLst || '').split(',').map(s => ncs(s)).filter(Boolean);

    targets.forEach(name => {
      if (!text.includes(name)) return;
      byCert.set(name, (byCert.get(name) || 0) + 1);
      fields.forEach(f => {
        if (!byNcs.has(f)) byNcs.set(f, new Map());
        const m = byNcs.get(f);
        if (!m.has(name)) m.set(name, { count: 0, samples: [] });
        const rec = m.get(name);
        rec.count += 1;
        /* 근거를 눌러 확인할 수 있게 공고를 두 건까지 들고 간다. 더 담으면
           응답만 커지고 화면에는 두 줄밖에 안 들어간다. */
        if (rec.samples.length < 2) {
          rec.samples.push({ title: j.recrutPbancTtl, inst: j.instNm, url: j.srcUrl || null });
        }
      });
    });
  });

  _postings = { fetchedAt: raw.fetchedAt || null, total: items.length, byNcs, byCert };
  return _postings;
}

/* ── 추천 ──────────────────────────────────────────────────────
   certs 는 catalog-db.certCatalog() 가 준 목록이다(국가 613 + 민간 30).
   라우트가 넘겨준다 — 이 모듈이 DB 를 직접 읽지 않게 해서 테스트에서 표만 바꿔
   끼울 수 있게 둔다.

   ── 무엇으로 줄 세우나 ──
   ① 직무와의 관련도(분야 매칭 순서)  ② 공고 언급 건수  ③ 등급  ④ 이름 순.

   ── 등급 순서가 '높은 것부터' 가 아니다 ──
   기술사·기능장은 **실무 경력이 있어야 응시할 수 있다**(기술사 4~9년). 자격 등급으로는
   맨 위지만 지금 대학생이 딸 수 있는 자격이 아니라, 위에 두면 추천 목록이 통째로
   '지금은 못 따는 것' 이 된다(실측: 정보통신 직무에서 정보관리기술사·컴퓨터시스템
   응용기술사가 SQLD 보다 위로 왔다). 그래서 **기사 → 산업기사 → 그 밖 → 기능사 →
   기능장 → 기술사** 순으로 둔다. */
const GRADE_RANK = { 기사: 0, 산업기사: 1, 기능사: 3, 기능장: 4, 기술사: 5 };
const gradeRank = c => (c.grade ? (GRADE_RANK[c.grade] ?? 2) : 2);

/* ── 같은 계열은 하나만 보여준다 ──────────────────────────────
   안 묶으면 목록이 한 자격의 변형으로 도배된다(실측):
     · 여행·숙박 직무 → 추천 8칸이 전부 '관광통역안내사(독어/러시아어/…)'
     · 사회복지 직무 → '1급/2급/3급 청소년상담사' + '1급/2급/3급 청소년지도사'
   학생에게 필요한 것은 **어떤 자격이 있는지**이고, 등급·언어는 그 자격을 고른
   다음에 검색으로 정확히 찾으면 된다(자격증 칸이 검색형이라 가능하다).

   계열 키는 괄호 이하와 등급 표기를 지운 이름이다. 지우고 나서 빈 문자열이 되면
   (등급만으로 된 이름은 없지만 방어) 원래 이름을 그대로 키로 쓴다. */
const GRADE_TOKENS = /(기술사|기능장|산업기사|기사|기능사|[123]급|Level\s*\d+)/g;
function familyOf(name) {
  const base = String(name || '')
    .replace(/\(.*$/, '')
    .replace(GRADE_TOKENS, '')
    .replace(/\s+/g, ' ')
    .trim();
  return base || String(name || '');
}

function recommend({ certs, jobMajor, jobMiddles, dept, limit = 8 }) {
  /* 좁은 것부터 본다. 세부직무가 있으면 그것만 쓴다 — 진출분야까지 합치면
     '경영·사무' 를 고른 사람에게 금융·보험 자격이 섞여 들어온다. */
  let fields = [];
  let basis = null;
  const middles = (jobMiddles || []).map(String);

  if (middles.length) {
    fields = [...new Set(middles.flatMap(c => KECO_MIDDLE_TO_NCS[c] || []))];
    basis = 'jobMiddle';
  }
  if (!fields.length && jobMajor != null && jobMajor !== '') {
    fields = KECO_MAJOR_TO_NCS[String(jobMajor)] || [];
    basis = 'jobMajor';
  }
  if (!fields.length && dept) {
    fields = DEPT_TO_NCS[dept] || [];
    basis = 'dept';
  }
  if (!fields.length) return { basis: null, fields: [], items: [], postings: null };

  const post = loadPostings(certs.map(c => c.id));

  const items = certs
    .map(c => {
      const { fields: certFields, source } = fieldsOf(c);
      /* 이 직무의 분야 목록에서 **몇 번째**로 걸렸는지가 곧 관련도다. KECO 매핑표의
         순서가 '앞엣것이 그 직무의 본류' 라서, 앞에서 걸린 자격이 위로 온다.
         안 걸리면 추천 대상이 아니다. */
      let rank = Infinity;
      let matched = null;
      certFields.forEach(f => {
        const at = fields.indexOf(f);
        if (at >= 0 && at < rank) { rank = at; matched = f; }
      });
      if (rank === Infinity) return null;

      /* 공고 건수는 **이 직무의 분야에서만** 센다. 전체 건수를 쓰면 '정보처리기사'
         처럼 어디서나 언급되는 자격이 모든 직무에서 1등이 된다. */
      let postings = 0;
      const samples = [];
      certFields.forEach(f => {
        const rec = post.byNcs.get(f)?.get(c.id);
        if (!rec) return;
        postings += rec.count;
        rec.samples.forEach(s => { if (samples.length < 2) samples.push(s); });
      });

      return {
        name: c.id,
        field: matched,
        /* 이 분야를 누가 정했나. 'qnet' = 큐넷이 자격에 붙여 준 직무분야,
           'croad' = 원본에 없거나 너무 넓어 우리가 보정한 것(FIELD_OVERRIDE).
           화면이 근거를 적을 때 둘을 섞어 말하지 않게 구분해 내보낸다. */
        fieldSource: source,
        kindLabel: c.kindLabel || null,
        grade: c.grade || null,
        issuer: issuerOf(c),
        postings,
        samples,
        _rank: rank,
      };
    })
    .filter(Boolean)
    .sort((a, b) =>
      a._rank - b._rank
      || b.postings - a.postings
      || gradeRank(a) - gradeRank(b)
      || a.name.localeCompare(b.name, 'ko'))
    /* 줄을 세운 **뒤에** 계열을 솎는다 — 먼저 솎으면 어느 등급을 남길지 정할
       기준이 없다. 지금은 위 정렬이 이미 '공고에 많이 뜨고 등급이 높은 것' 을
       앞에 뒀으므로, 계열마다 첫 번째가 곧 대표다. */
    .filter((c, _i, all) => all.find(x => familyOf(x.name) === familyOf(c.name)) === c)
    .slice(0, limit)
    .map(({ _rank, ...rest }) => rest);

  return {
    basis,
    fields,
    items,
    /* 공고 근거의 출처를 화면이 그대로 적을 수 있게 함께 준다. 화면에서 문구를
       따로 만들면 표본 수가 바뀌었을 때 두 곳이 갈린다. */
    postings: { source: '공공기관 채용공고(잡알리오)', total: post.total, fetchedAt: post.fetchedAt },
  };
}

