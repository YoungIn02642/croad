/* 접두어가 겹칠 때 **가장 긴 것**이 이긴다. '경매사' 와 '경영지도사' 처럼 앞글자가
   같은 항목이 늘어나도 표의 순서에 결과가 좌우되지 않게 한다. */
function fieldsOf(cert) {
  const name = String(cert?.id ?? cert?.name ?? '');
  let best = null;
  for (const [prefix, fields] of FIELD_OVERRIDE) {
    if (!name.startsWith(prefix)) continue;
    if (!best || prefix.length > best[0].length) best = [prefix, fields];
  }
  if (best) return { fields: best[1].map(ncs), source: 'croad' };
  const f = ncs(cert.field);
  return { fields: f ? [f] : [], source: 'qnet' };
}

