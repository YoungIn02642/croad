/* ── 응답 정리 ────────────────────────────────────────────────
   모델이 코드펜스를 붙이거나 앞뒤에 말을 얹는 일이 잦다. 첫 '{' 부터 마지막 '}' 까지만
   잘라서 파싱한다. 파싱이 안 되면 초안을 주지 않는다 — 깨진 문장을 자소서에 넣게
   두는 것보다 "실패했다"고 말하는 편이 낫다. */
function parseDraft(raw) {
  const text = String(raw || '');
  const start = text.indexOf('{');
  const end = text.lastIndexOf('}');
  if (start < 0 || end <= start) throw new Error('AI 응답을 읽지 못했습니다.');

  let data;
  try { data = JSON.parse(text.slice(start, end + 1)); }
  catch { throw new Error('AI 응답을 읽지 못했습니다.'); }

  const draft = String(data.draft || '').trim();
  if (!draft) throw new Error('AI 가 초안을 만들지 못했습니다.');

  return {
    draft,
    blanks: toLines(data.blanks),
    coach: toCoach(data.coach),
    review: toLines(data.review),
    /* 서버가 직접 센다. 모델이 "빈칸 3개" 라고 말해도 실제 문장과 다를 수 있어서,
       화면에 띄우는 숫자는 문자열에서 세는 값만 믿는다. */
    blankCount: GUIDE.countBlanks(draft),
    cliches: GUIDE.findCliches(draft),
    aiTells: GUIDE.findAiTells(draft),
  };
}

function toLines(v) {
  if (!Array.isArray(v)) return [];
  return v.map(x => String(x || '').trim()).filter(Boolean).slice(0, 5);
}

/* 칸별 되짚기. key 가 S·T·A·R 가 아니면 버린다 — 화면이 그 키로 STAR 입력칸을 찾아
   붙이므로, 엉뚱한 키가 들어오면 어디에도 안 붙고 조용히 사라진다.
   같은 칸을 두 번 말하는 것도 첫 줄만 남긴다(모델이 종종 중복해서 낸다). */
function toCoach(v) {
  if (!Array.isArray(v)) return [];
  const seen = new Set();
  const out = [];
  for (const x of v) {
    const key = String(x?.key || '').trim().toUpperCase().slice(0, 1);
    if (!['S', 'T', 'A', 'R'].includes(key) || seen.has(key)) continue;
    const missing = String(x?.missing || '').trim();
    const ask = String(x?.ask || '').trim();
    if (!missing && !ask) continue;
    seen.add(key);
    out.push({ key, missing, ask });
  }
  return out;
}

/* ── 분량 상한을 코드로 지킨다 (사용자 지시 2026-09-05) ────────────────────────
   지금까지 상한은 **프롬프트로 부탁만** 하고 생성 뒤 확인을 안 했다. 그래서 넘겨서
   나오면 그대로 나갔다. 모자란 것은 사용자가 채우면 되지만 넘친 것은 **제출이 막힌다** —
   자소서 입력칸이 글자 수로 자르기 때문에 뒤가 통째로 날아간다.

   ── 왜 문장 단위로 자르나 ──
   글자 수로 뚝 자르면 "…했습니" 처럼 말이 끊긴다. 그건 초안이 아니라 사고다.
   상한 안에 들어가는 **마지막 완결 문장까지만** 남긴다. 한국어 문장은 '다.' '요.' 로
   끝나는 것이 대부분이라 종결 부호로 가른다.

   ── 자르기는 마지막 수단이다 ──
   라우트가 먼저 한 번 다시 부른다(짧게 쓰라고 알려서). 그래도 넘으면 그때 자른다.
   자른 사실은 응답의 trimmed 로 알려서 화면이 "분량에 맞춰 줄였다" 고 말할 수 있게 한다. */
const lenOf = s => [...String(s || '')].length;

function fitToLimit(draft, limit) {
  const max = Number(limit) > 0 ? Number(limit) : 0;
  const text = String(draft || '');
  if (!max || lenOf(text) <= max) return { draft: text, trimmed: false };

  /* 종결 부호 뒤에서 끊는다. 부호를 문장에 붙여 둔 채 잘라야 '다' 만 남지 않는다.
     **뒤따르는 공백·줄바꿈도 문장에 붙여서** 자른다 — split 으로 공백을 버리면
     이어 붙일 때 "첫 문장입니다.두 번째" 처럼 사이가 사라진다(실측). */
  const parts = text.match(/[^.!?…]*[.!?…]+[\s]*|[^.!?…]+$/g) || [text];
  let out = '';
  for (const p of parts) {
    if (lenOf(out + p) > max) break;
    out += p;
  }
  /* 첫 문장부터 상한을 넘는 극단(상한이 아주 짧거나 한 문장이 통째로 길다)에서는
     빈 초안을 줄 수 없으므로 글자 수로 자르고 말줄임을 붙인다.
     **말줄임표도 한 글자를 먹는다** — 상한이 1이면 붙일 자리가 없다(테스트가 잡았다).
     라우트는 상한을 200 아래로 안 내리지만, 이 함수는 혼자서도 옳아야 한다. */
  if (!out.trim()) {
    out = max <= 1
      ? [...text].slice(0, max).join('')
      : [...text].slice(0, max - 1).join('') + '…';
  }
  return { draft: out.trim(), trimmed: true };
}

