/* ════════════════════════════════════════════════════════════
   목록 미리보기 — 본문에서 마크다운 기호를 걷어내고 자른다

   ── 왜 필요한가 (실측 2026-09-13) ──
   본문은 마크다운인데 목록은 **글자 그대로 보여주는 자리**다. 그대로 자르면
   '**글자 수가 빽빽한 문항**(500~600자)' 이나 '## 1단계' 처럼 별표와 우물 정이
   목록에 그대로 나온다. 카드가 미리보기에 두 줄을 쓰면서 더 도드라졌다.

   ── 지우기만 한다 ──
   여기서 마크다운을 해석하려 들면 화면 두 곳(목록·상세)이 서로 다른 파서를 갖게
   된다. 상세는 Markdown.render 가 그리고, 여기서는 기호만 떼고 남은 글자를 쓴다.

   ── 자르는 것은 기호를 걷어낸 뒤다 ──
   먼저 자르면 120자 중 일부가 화면에 안 보이는 기호다. 같은 120자라도 실제로
   읽히는 글자 수가 글마다 달라진다.
   ════════════════════════════════════════════════════════════ */

const LIMIT = 120;

function previewOf(body) {
  return String(body || '')
    .replace(/```[\s\S]*?```/g, ' ')            // 코드 덩이는 통째로 뺀다
    .replace(/!\[[^\]]*\]\([^)]*\)/g, ' ')        // 이미지
    .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')     // 링크는 글자만 남긴다
    .replace(/^\s{0,3}#{1,6}\s+/gm, '')          // 제목
    .replace(/^\s{0,3}>\s?/gm, '')               // 인용
    .replace(/^\s{0,3}([-*+]|\d+\.)\s+/gm, '')   // 목록 기호
    .replace(/^\s{0,3}([-*_])(\s*\1){2,}\s*$/gm, ' ')  // 가로줄
    /* ── 강조는 마크다운이 강조로 읽는 자리만 뗀다 ──────────────────
       두 가지를 지킨다(둘 다 실측으로 걸렸다):
         · 여는 기호 뒤·닫는 기호 앞에 공백이 없어야 한다 — 없으면 'a * b * c' 의
           곱셈 별표가 지워진다.
         · 밑줄은 낱말 안에서는 강조가 아니다 — 없으면 'user_id 와 post_id' 가
           'userid 와 postid' 가 된다. 별표와 밑줄을 따로 두는 이유가 이것이다. */
    .replace(/(?<![\w*])\*\*(?!\s)([\s\S]*?)(?<!\s)\*\*(?![\w*])/g, '$1')  // **굵게**
    .replace(/(?<![\w_])__(?!\s)([\s\S]*?)(?<!\s)__(?![\w_])/g, '$1')      // __굵게__
    .replace(/(?<![\w*])\*(?!\s)([^\n*]*?)(?<!\s)\*(?![\w*])/g, '$1')      // *기울임*
    .replace(/(?<![\w_])_(?!\s)([^\n_]*?)(?<!\s)_(?![\w_])/g, '$1')        // _기울임_
    .replace(/`([^`]*)`/g, '$1')                 // 인라인 코드
    .replace(/\s+/g, ' ')
    .trim()
    .slice(0, LIMIT);
}

module.exports = { previewOf, LIMIT };
