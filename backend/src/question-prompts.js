const specFor = id => SPECS[id] || null;

/* ── 골격 + 분량 배분 (Context 에 들어간다) ────────────────────
   share 를 목표 글자 수로 환산해서 같이 준다. 퍼센트만 주면 모델이 문단 전체 길이를
   모른 채 배분해야 해서 큰 덩이가 계속 커진다(실측한 증상이 정확히 이것이다). */
function frameBlock(id, { label, limit } = {}) {
  const spec = specFor(id);
  if (!spec) return null;
  const total = Number(limit) || 600;
  /* ── 하한이 없으면 배분표가 '상한표' 로 읽힌다 (실측 2026-09-01) ────────────
     처음엔 배분(%)과 덩이별 글자 수만 줬다. 쏠림은 사라졌는데 **여섯 유형 전부가 목표
     글자 수의 37~75% 에서 끝났다**(지원동기 222자/600자). 원인이 둘이었다.
       (1) 덩이별 글자 수를 **넘지 말아야 할 선**으로 읽고 모든 덩이를 짧게 썼다.
       (2) "재료가 없으면 대괄호로 비워서라도 자리를 채운다" 고 적어 놨더니,
           **대괄호 하나로 120자짜리 덩이를 때웠다.** 빈칸은 자리를 채우지 않는다.
     그래서 합계 하한(목표의 90%)을 못 박고, 빈칸이 분량을 대신하지 못한다고 명시한다. */
  const floor = Math.round(total * 0.9);
  /* ── 글자 수 하한만으로는 길이가 안 늘었다 (실측 2026-09-01) ────────────────
     "540자 미만이면 틀린 답" 을 걸어도 46~66% 에서 끝났다. 모델은 한국어 글자를 세지
     못한다 — 지킬 수 없는 규칙이라 무시된다. **문장 수는 셀 수 있다.** 그래서 덩이마다
     목표 문장 수를 같이 준다.

     ── 65 → 54 (합격 자소서 72편 실측 2026-09-08) ──────────────────────────
     65 는 **모델이 뱉은 문장**의 평균(63~78자)에서 잡은 값이었다. 그런데 이 상수가
     하는 일은 "합격 자소서처럼 쓰려면 몇 문장이어야 하는가" 를 정하는 것이므로,
     기준은 모델 출력이 아니라 **합격 자소서**여야 한다. 재 보니 평균·중앙값 모두
     54자였다(범위 31~80, n=72. backend/scripts/analyze-samples.js).
     65 로 나누면 문장 수를 20% 적게 요구한다 — 600자 문항에서 9문장을 시키는데
     합격 자소서는 11문장이다. 위에 적힌 "목표의 37~75% 에서 끝났다" 는 증상과
     방향이 같다. 짧게 끝나는 원인 중 하나를 상수가 만들고 있었다.
     부수 효과로 문장이 짧아진다 — 한 문장에 여러 절을 이어 붙인 만연체가 줄어든다. */
  const SENT = 54;
  const lines = spec.parts.map((p, i) => {
    const chars = Math.round(total * p.share / 100);
    const sents = Math.max(1, Math.round(chars / SENT));
    const head = `  ${'①②③④⑤⑥'[i] || `(${i + 1})`} ${p.key} — ${p.label}`
      + `  [약 ${p.share}%, ${chars}자 · **${sents}문장**]`;
    const must = (p.must || []).map(m => `     · 반드시: ${m}`);
    return [head, ...must, `     · 이렇게 쓰면 탈락: "${p.bad}"`].join('\n');
  });
  return [
    `이 문항(${label || id})을 쓰는 순서와 **분량 배분** — 목표 ${total}자 기준:`,
    ...lines,
    /* ── 비율 규칙은 전부 '상대 조건' 이라 깎아서도 통과한다 (심사 지적 2026-09-01) ──
       "④가 ③보다 길게" · "③은 1/4 이하" 는 ④를 늘려도 ③을 줄여도 통과다. 모델은 싼 쪽
       (깎기)을 골랐고, 그 대가로 지원자의 유일한 검증 가능한 사실(80명 설문·최우수상)이
       ③에서 잘려 나갔다. 그래서 **덩이마다 절대 하한**을 같이 건다. */
    `  ※ 위 글자 수는 **상한이 아니라 목표치다.** 각 덩이를 그 분량만큼 채워 써라 —`
      + ` **어느 덩이도 제 목표 글자 수의 70% 아래로 내려가면 안 된다.**`
      + ` 다른 덩이를 깎아서 비율을 맞추지 마라.`,
    `  ※ 전체 **${spec.parts.reduce((a, p) => a + Math.max(1, Math.round(total * p.share / 100 / SENT)), 0)}문장**`
      + `(약 ${floor}~${total}자)으로 쓴다. **문장 수를 먼저 맞추고 내용을 채워라.**`,
    `  ※ 전체가 **${floor}자 미만이면 틀린 답이다.** 짧게 끝내지 마라.`
      + ` 한 덩이가 전체의 절반을 넘어도 틀린 답이다 — 재료가 많은 덩이를 길게 쓰지 마라.`,
    `  ※ **대괄호는 분량을 대신하지 못한다.** 모르는 값이 있는 덩이도 그 덩이의 글자 수를 채운다`
      + ` — 모르는 값 하나만 대괄호로 비우고, 나머지는 아는 사실과 판단으로 문장을 만든다.`
      + ` 한 덩이에 대괄호는 **1개까지**다.`,
  ].join('\n');
}

/* ── 유형 전용 규칙 (Restriction 에 붙는다) ──────────────────── */
function typeRules(id) {
  const spec = specFor(id);
  return spec ? spec.rules.slice() : [];
}

/* ── 유형별 나쁜 예 (Restriction 맨 뒤) ────────────────────────
   일반 나쁜 예(draft-coach 규칙 14)는 STAR 문항 기준이라 지원동기·성격 장단점에는
   안 맞는다. 유형마다 실제로 나오는 모양이 다르므로 유형 예를 쓴다. */
function badExampleRule(id) {
  const spec = specFor(id);
  if (!spec?.badExample) return null;
  const { text, missing } = spec.badExample;
  return `아래는 **이 유형에서 절대로 내놓으면 안 되는 답**이다. 문법과 순서는 맞지만 정보가 없다.\n`
    + `   "${text}"\n`
    + `   빠진 것: ${missing.join(' · ')}\n`
    + `   이것들을 **주어진 사실로만** 채워라(없는 것은 지어내지 말고 대괄호로 비운다).`;
}

const starModeOf = id => specFor(id)?.starMode || null;

module.exports = { SPECS, specFor, frameBlock, typeRules, badExampleRule, starModeOf };
