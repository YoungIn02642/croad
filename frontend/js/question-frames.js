      /* '협업' 만 있고 **'협력'·'소통'** 이 없었다(실측 2026-09-08). 실제 문항은
         "소통과 협력은 무엇인지"·"소통하고 협력하면서 융화를" 처럼 이 말들을 훨씬 자주
         쓴다. 셋 다 같은 유형이다 — 묻는 것은 사람과 일하는 방식 하나다. */
      match: /협업|협력|소통|융화|공동\s*과제|갈등|팀\s*워크|팀\s*원|유관\s*부서|의견\s*차이|조율|조정|설득|함께/,
      frame: '① 협업에서 무엇을 중요하게 여기게 됐는지 먼저 선언 → ② 팀 구성과 내 역할 '
        + '→ ③ 의견 차이(무엇이 어떻게 갈렸는지) → ④ 내가 한 조정 방식(구체적 행동) → ⑤ 합의된 결론',
