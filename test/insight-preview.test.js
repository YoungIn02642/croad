/* 목록 미리보기 — 본문(마크다운)에서 기호를 걷어내고 자른다.
   DB 도 네트워크도 부르지 않는다.

   ── 이 테스트가 지키는 것 ──
   1) **목록에 기호가 새지 않는다** — 별표·우물 정이 그대로 보이던 자리다.
   2) **글자는 지우지 않는다** — 기호만 떼고 내용은 그대로 남아야 한다.
   3) **강조가 아닌 별표는 살린다** — 'a * b * c' 의 곱셈까지 지우면 뜻이 바뀐다.
   4) **자르는 것은 기호를 걷어낸 뒤다** — 먼저 자르면 읽히는 글자 수가 글마다 다르다. */
const P = require('../backend/src/insight-preview.js');

let pass = 0, fail = 0;
function ok(name, cond, extra = '') {
  if (cond) { pass++; console.log(`  PASS  ${name} ${extra}`); }
  else { fail++; console.log(`  FAIL  ${name} ${extra}`); }
}
const pv = P.previewOf;

console.log('── 1. 기호를 걷어낸다 ──');
ok('굵게', pv('**글자 수가 빽빽한 문항**(500~600자)') === '글자 수가 빽빽한 문항(500~600자)');
ok('문장 중간의 굵게', pv('이유는 **무엇을 먼저 할지** 기준이 없어서입니다.')
   === '이유는 무엇을 먼저 할지 기준이 없어서입니다.');
ok('밑줄 굵게', pv('__굵게__ 입니다') === '굵게 입니다');
ok('기울임', pv('_기울임_ 과 보통 글') === '기울임 과 보통 글');
ok('제목', pv('## 1단계') === '1단계');
ok('제목 여섯 단계', pv('###### 깊은 제목') === '깊은 제목');
ok('목록 기호', pv('- 첫 문장에 결론\n- 근거는 숫자로') === '첫 문장에 결론 근거는 숫자로');
ok('번호 목록', pv('1. 하나\n2. 둘') === '하나 둘');
ok('인용', pv('> 인용한 말') === '인용한 말');
ok('인라인 코드', pv('`코드` 도 글자로') === '코드 도 글자로');
ok('링크는 글자만 남는다', pv('[C:road](https://example.com) 에서') === 'C:road 에서');
ok('이미지는 통째로 빠진다', pv('![사진](a.png) 본문') === '본문');
ok('코드 덩이는 통째로 빠진다', pv('```\n코드덩이\n```\n실제 본문') === '실제 본문');
ok('가로줄', pv('앞 문장\n\n---\n\n뒤 문장') === '앞 문장 뒤 문장');

console.log('\n── 2. 글자는 지우지 않는다 ──');
ok('기호가 없으면 그대로', pv('평범한 한 줄입니다.') === '평범한 한 줄입니다.');
ok('곱셈 별표는 살린다', pv('a * b * c 는 그대로') === 'a * b * c 는 그대로',
   '여는 기호 뒤에 공백이 있으면 마크다운도 강조로 읽지 않는다');
ok('밑줄 낀 식별자는 살린다', pv('user_id 와 post_id 를 맞춘다') === 'user_id 와 post_id 를 맞춘다');
ok('줄바꿈은 공백 하나로', pv('첫 줄\n\n\n둘째 줄') === '첫 줄 둘째 줄');

console.log('\n── 3. 자르기 ──');
ok('상한까지만 남는다', pv('가'.repeat(300)).length === P.LIMIT, `→ ${P.LIMIT}자`);
ok('기호를 걷어낸 뒤에 자른다', pv('**' + '나'.repeat(300) + '**').length === P.LIMIT,
   '먼저 잘랐다면 별표 네 개만큼 짧아진다');
ok('짧은 글은 그대로', pv('짧다').length === 2);

console.log('\n── 4. 빈 값 ──');
ok('빈 문자열', pv('') === '');
ok('null', pv(null) === '');
ok('undefined', pv(undefined) === '');
ok('공백뿐', pv('   \n  ') === '');

console.log(`\n결과: ${pass} 통과 / ${fail} 실패`);
process.exit(fail ? 1 : 0);
